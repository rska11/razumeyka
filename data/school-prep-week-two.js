import {
  choice as choiceBuilder,
  memory as memoryBuilder,
  quiz as quizBuilder,
  sequence as sequenceBuilder,
  symbolOption,
} from './school-prep-mission-builders.js';

const TONES = ['blue', 'purple', 'pink', 'orange', 'green', 'cyan'];

function options(items) {
  return items.map((item, index) => {
    const [label, symbol = label, tone = TONES[index % TONES.length]] = Array.isArray(item) ? item : [item];
    return symbolOption(`o${index}`, label, symbol, tone);
  });
}

function pick(id, chapter, skill, title, prompt, items, correct, hint, success, mode = 'single') {
  return choiceBuilder(
    id, chapter, skill, title, prompt, options(items),
    correct.map((index) => `o${index}`), hint, success, mode,
  );
}

function order(id, chapter, skill, title, prompt, items, correct, hint, success) {
  return sequenceBuilder(
    id, chapter, skill, title, prompt, options(items),
    correct.map((index) => `o${index}`), hint, success,
  );
}

function pairs(id, chapter, skill, title, prompt, items, success) {
  const cards = items.flatMap(([pair, left, right]) => [
    { pair, label: left, emoji: left },
    { pair, label: right, emoji: right },
  ]);
  return memoryBuilder(id, chapter, skill, title, prompt, cards, success);
}

function action(id, chapter, skill, title, prompt, actions, success) {
  return {
    id,
    type: 'action',
    chapter,
    skill,
    title,
    prompt,
    actions: actions.map(([actionTitle, text, visual = 'idea']) => ({ title: actionTitle, text, visual })),
    success,
  };
}

function sort(id, chapter, skill, title, prompt, groups, items, hint, success) {
  return {
    id,
    type: 'sort',
    chapter,
    skill,
    title,
    prompt,
    groups: groups.map(([groupId, label, emoji]) => ({ id: groupId, label, emoji })),
    items: items.map(([label, group, emoji = label]) => ({ label, group, emoji })),
    hint,
    success,
  };
}

function exam(id, chapter, skill, title, prompt, questions, success) {
  return quizBuilder(
    id,
    chapter,
    skill,
    title,
    prompt,
    questions.map(([questionPrompt, answers, correct]) => ({
      prompt: questionPrompt,
      options: answers.map((label, index) => ({ id: `q${index}`, label })),
      correct: `q${correct}`,
    })),
    success,
  );
}

