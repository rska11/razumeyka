// Канонические ссылки страниц.
//
// Зачем обёртка вместо простого объекта: Яндекс отклоняет заявку на переезд
// сайта (смену главного зеркала), если на страницах НОВОГО адреса есть
// атрибут rel="canonical" — это первый пункт в списке причин отказа
// (yandex.ru/support/webmaster/ru/yandex-indexing/site-addresses.html).
//
// Поэтому на время склейки зеркал канонические ссылки выключаются
// переменной окружения SITE_MOVE=1 в .env. После того как Яндекс сменит
// главное зеркало (обычно до двух недель), переменную нужно убрать и
// выкатить заново — canonical снова начнут отдаваться.

export function canonical(path: string) {
  if (process.env.SITE_MOVE === '1') return undefined;
  return { canonical: path };
}
